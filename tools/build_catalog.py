#!/usr/bin/env python3
"""Compiles tools/catalog_src/*.py into js/catalog.js (the file the website loads).   python tools/build_catalog.py"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.dont_write_bytecode = True
sys.path.insert(0, str(ROOT / "tools"))
from catalog_src import CATEGORIES, ENTRIES  # noqa: E402


def main():
    seen = set()
    for e in ENTRIES:
        assert e["id"] not in seen, f"duplicate entry id {e['id']}"
        seen.add(e["id"])
    counts = {c["id"]: sum(1 for e in ENTRIES if e["cat"] == c["id"]) for c in CATEGORIES}
    cats = [dict(c, count=counts[c["id"]]) for c in CATEGORIES]
    payload = {"categories": cats, "entries": ENTRIES}
    out = ROOT / "js" / "catalog.js"
    out.parent.mkdir(exist_ok=True)
    out.write_text("/* AUTO-GENERATED by tools/build_catalog.py - edit tools/catalog_src/*.py instead */\nwindow.CATALOG = "
                   + json.dumps(payload, ensure_ascii=False, separators=(",", ":")) + ";\n", encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)}: {len(cats)} categories, {len(ENTRIES)} functions, {out.stat().st_size / 1024:.0f} KB")


if __name__ == "__main__":
    main()
