#!/usr/bin/env python3
"""Runs every project solution, stores the expected output and writes js/projects.js.   python tools/build_projects.py"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.dont_write_bytecode = True
sys.path[:0] = [str(ROOT / "py"), str(ROOT / "tools")]
import os
os.chdir(ROOT)
import numpy as np  # noqa: E402
import runner  # noqa: E402
from projects_src import PROJECTS  # noqa: E402


def main():
    runner.init()
    out, bad = [], 0
    for p in PROJECTS:
        pj = {k: v for k, v in p.items() if k != "steps"}
        pj["steps"] = []
        for i, s in enumerate(p["steps"], 1):
            ns = runner._namespace()
            res, _ = runner._execute(p["prelude"] + "\n" + s["solution"], ns, "b", 25)
            if not res["ok"] or "answer" not in ns:
                print("SOLUTION FAILS", p["id"], i, s["title"], res.get("error"))
                bad += 1
                continue
            ans = ns["answer"]
            st = dict(s, id=f"{p['id']}-{i}", n=i, expected=runner.encode(ans), expected_text=runner.expected_text(ans),
                      shape=list(np.asarray(ans).shape), dtype=str(np.asarray(ans).dtype))
            # the starter must NOT already pass
            chk = json.loads(runner.check(p["prelude"] + "\n" + s["starter"], json.dumps(st["expected"]), "answer", s["rtol"], s["atol"]))
            if chk["ok"]:
                print("STARTER ALREADY PASSES", p["id"], i)
                bad += 1
            # the solution must pass its own check
            chk = json.loads(runner.check(p["prelude"] + "\n" + s["solution"], json.dumps(st["expected"]), "answer", s["rtol"], s["atol"]))
            if not chk["ok"]:
                print("SOLUTION DOES NOT PASS CHECK", p["id"], i, chk)
                bad += 1
            pj["steps"].append(st)
        out.append(pj)
    path = ROOT / "js" / "projects.js"
    path.write_text("/* AUTO-GENERATED by tools/build_projects.py */\nwindow.PROJECTS = " + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n", encoding="utf-8")
    print(f"wrote {path.relative_to(ROOT)}: {len(out)} projects, {sum(len(p['steps']) for p in out)} steps, {bad} problems")
    for p in out:
        for s in p["steps"]:
            print(f"  {s['id']:14} {s['title'][:34]:34} -> {s['expected_text'][:70].replace(chr(10), ' ')}")
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
